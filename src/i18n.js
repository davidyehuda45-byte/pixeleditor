const DICTIONARIES = { id, en };

export function getDictionary(lang) {
  return DICTIONARIES[lang] || id;
}

export function translate(lang, key, vars) {
  const dict = getDictionary(lang);
  let text = dict[key] ?? id[key] ?? key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? String(vars[name]) : `{${name}}`));
  }
  return text;
}

export function formatTime(iso, lang = 'id') {
  if (!iso) return '—';
  try {
    const d = typeof iso === 'number' ? new Date(iso) : new Date(iso);
    return d.toLocaleString(lang === 'id' ? 'id-ID' : 'en-US', { hour: '2-digit', minute: '2-digit', day: '2-digit', month: 'short' });
  } catch {
    return '—';
  }
}
