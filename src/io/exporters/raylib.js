/**
 * Raylib C Header Exporter
 * Produces clean C structure with Rectangle atlas bounds and animation tags.
 */

export function buildRaylibHeader(sheetMeta, imageFileName, opts = {}) {
  const name = opts.baseName || sheetMeta.name || 'sprite';
  const safeName = name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  const frameCount = sheetMeta.frames.length;
  const tags = opts.tags || sheetMeta.tags || [];

  let rectsCode = '';
  sheetMeta.frames.forEach((f, idx) => {
    rectsCode += `    { ${f.x}.0f, ${f.y}.0f, ${f.w}.0f, ${f.h}.0f }, // [${idx}] ${f.name || ''}\n`;
  });

  let tagsCode = '';
  if (tags && tags.length > 0) {
    tags.forEach((t) => {
      const tagSafe = t.name.replace(/[^a-zA-Z0-9_]/g, '_').toUpperCase();
      tagsCode += `#define ${safeName.toUpperCase()}_ANIM_${tagSafe}_FROM ${t.from}\n`;
      tagsCode += `#define ${safeName.toUpperCase()}_ANIM_${tagSafe}_TO   ${t.to}\n`;
    });
  }

  const header = `/**
 * Generated by PixelForge for Raylib 5.0+
 * Asset: ${name}
 * Texture: ${imageFileName} (${sheetMeta.width}x${sheetMeta.height})
 */

#ifndef ${safeName.toUpperCase()}_ATLAS_H
#define ${safeName.toUpperCase()}_ATLAS_H

#include "raylib.h"

#define ${safeName.toUpperCase()}_FRAME_COUNT ${frameCount}
#define ${safeName.toUpperCase()}_FRAME_WIDTH ${sheetMeta.frames[0]?.w || 16}
#define ${safeName.toUpperCase()}_FRAME_HEIGHT ${sheetMeta.frames[0]?.h || 16}

${tagsCode}
// Frame bounding rectangles in the texture atlas
static const Rectangle ${safeName}_rects[${frameCount}] = {
${rectsCode}};

/**
 * Example usage:
 * Texture2D texture = LoadTexture("${imageFileName}");
 * DrawTextureRec(texture, ${safeName}_rects[current_frame], (Vector2){ posX, posY }, WHITE);
 */

#endif // ${safeName.toUpperCase()}_ATLAS_H
`;

  return header;
}

