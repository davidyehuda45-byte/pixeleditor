/**
 * LÖVE (Love2D) Lua Exporter
 * Generates ready-to-use Quad definitions and animations in Lua.
 */

export function buildLove2DAtlas(sheetMeta, imageFileName, opts = {}) {
  const name = opts.baseName || sheetMeta.name || 'sprite';
  const tags = opts.tags || sheetMeta.tags || [];
  const safeName = name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  const W = sheetMeta.width;
  const H = sheetMeta.height;

  let quadsCode = '';
  sheetMeta.frames.forEach((f, idx) => {
    quadsCode += `  love.graphics.newQuad(${f.x}, ${f.y}, ${f.w}, ${f.h}, ${W}, ${H}), -- [${idx + 1}]\n`;
  });

  let tagsCode = '';
  if (tags && tags.length > 0) {
    tags.forEach((t) => {
      tagsCode += `    ["${t.name}"] = { from = ${t.from + 1}, to = ${t.to + 1} },\n`;
    });
  }

  const luaScript = `-- Generated by PixelForge for LÖVE (Love2D)
-- Asset: ${name}
-- Texture: ${imageFileName} (${W}x${H})

local ${safeName} = {}

function ${safeName}.load()
  ${safeName}.image = love.graphics.newImage("${imageFileName}")
  ${safeName}.image:setFilter("nearest", "nearest")

  ${safeName}.quads = {
${quadsCode}  }

  ${safeName}.animations = {
${tagsCode}  }
end

function ${safeName}.draw(frameIndex, x, y, r, sx, sy)
  local quad = ${safeName}.quads[frameIndex]
  if quad then
    love.graphics.draw(${safeName}.image, quad, x or 0, y or 0, r or 0, sx or 1, sy or 1)
  end
end

return ${safeName}
`;

  return luaScript;
}
